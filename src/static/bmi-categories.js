function getBmiCategory(bmi) {
    if (bmi < 18.5) {
        return {
            label: 'Вага недостатня.',
            description: 'Є збільшений ризик розладів здоров\'я, таких як аменорея у жінок (відсутність менструації), крихкість кісток та відсутність поживних речовин для здорового функціонування всіх систем організму.',
        };
    }
    if (bmi < 25) {
        return {
            label: 'Вага в нормі.',
            description: 'Ідеальний ІМТ для людей до 25 років - 22-23. Якщо ІМТ наближається до показника 25, почніть контролювати об\'єм талії та пам\'ятайте про фізичну активність.',
        };
    }
    if (bmi < 30) {
        return {
            label: 'Надмірна вага.',
            description: 'Є збільшений ризик серцево-судинних захворювань, діабету, порушень статевої функції та інших захворювань. Намагайтеся зменшити вагу, почніть правильно харчуватися і займатися спортом.',
        };
    }
    return {
        label: 'Ожиріння.',
        description: 'Вам потрібно схуднути до більш низьких значень ІМТ для здорового життя. Високий ІМТ пов\'язаний з збільшеним ризиком смертності від будь-яких причин, включаючи діабет, серцево-судинні захворювання, гіпертонію та артрит.',
    };
}

if (typeof module !== 'undefined' && module.exports) {
    module.exports = getBmiCategory;
}
